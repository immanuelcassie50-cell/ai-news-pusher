function extractText(jsContent) {
  const lines = jsContent.split("\n");
  const texts = [];
  for (const line of lines) {
    const m = line.match(/(?:sectionName|title|bigIdea|footer|desc|goal|hint|setup|name|line|t|w|ex)[:\s]*"(.*?)"/);
    if (m) {
      let t = m[1];
      t = t.replace(/\\"/g, '"').replace(/\\\\/g, "\\").replace(/\\n/g, " ");
      if (t.length > 0 && t.length < 100) texts.push(t);
    }
  }
  return texts;
}

