def copy_template():
    """复制模板到临时工作目录"""
    work_dir = "/tmp/xlsx_sex_ed"
    if os.path.exists(work_dir):
        shutil.rmtree(work_dir)
    shutil.copytree(TEMPLATE_DIR, work_dir)
    return work_dir

def pack_xlsx(work_dir, output_path):
    """打包生成xlsx文件"""
    with zipfile.ZipFile(output_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        for root, dirs, files in os.walk(work_dir):
            for file in files:
                file_path = os.path.join(root, file)
                arcname = os.path.relpath(file_path, work_dir)
                zf.write(file_path, arcname)

def create_shared_strings(strings):
    """创建sharedStrings.xml内容"""
    count = len(strings)
    items = []
    for s in strings:
        escaped = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        items.append(f'  <si><t>{escaped}</t></si>')
    return f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="{count}" uniqueCount="{count}">
{chr(10).join(items)}
</sst>'''

def create_sheet_xml(rows_data, col_widths):
    """创建sheet1.xml内容"""
    cols_xml = []
    for i, w in enumerate(col_widths, 1):
        cols_xml.append(f'    <col min="{i}" max="{i}" width="{w}" customWidth="1"/>')

    rows_xml = []
    for row_idx, row in enumerate(rows_data, 1):
        cells = []
        for cell in row:
            if cell is None:
                continue
            addr = cell['addr']
            style = cell.get('s', '0')
            vtype = cell.get('t', 's')
            value = cell.get('v', '')
            formula = cell.get('f', None)

            if formula:
                cells.append(f'    <c r="{addr}" s="{style}"><f>{formula}</f><v></v></c>')
            elif vtype == 's':
                cells.append(f'    <c r="{addr}" t="s" s="{style}"><v>{value}</v></c>')
            else:
                cells.append(f'    <c r="{addr}" s="{style}"><v>{value}</v></c>')

        rows_xml.append(f'  <row r="{row_idx}">\n' + '\n'.join(cells) + '\n  </row>')

    return f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheetViews>
    <sheetView tabSelected="1" workbookViewId="0"/>
  </sheetViews>
  <sheetFormatPr defaultRowHeight="15" x14ac:dyDescent="0.25" xmlns:x14ac="http://schemas.microsoft.com/office/spreadsheetml/2009/9/ac"/>
  <cols>
{chr(10).join(cols_xml)}
  </cols>
  <sheetData>
{chr(10).join(rows_xml)}
  </sheetData>
  <pageMargins left="0.7" right="0.7" top="0.75" bottom="0.75" header="0.3" footer="0.3"/>
</worksheet>'''

def update_workbook(work_dir, sheet_name):
    """更新workbook.xml中的工作表名称"""
    wb_path = os.path.join(work_dir, 'xl', 'workbook.xml')
    with open(wb_path, 'r', encoding='utf-8') as f:
        content = f.read()
    content = content.replace('个人学习路径规划表', sheet_name)
    with open(wb_path, 'w', encoding='utf-8') as f:
        f.write(content)

