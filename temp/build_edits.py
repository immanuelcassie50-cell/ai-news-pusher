def slots(slide):
    """Return list of (slot_id, max_chars, role, level, font_size) for editable slots of a slide."""
    out = []
    for sid, s in SM[str(slide)]["slots"].items():
        if s.get("editable"):
            out.append((sid, s["max_chars"], s["role"], s.get("level", 0), s.get("font_size", 14)))
    return out

