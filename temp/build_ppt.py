# 配色
DEEP_BLUE = RGBColor(0x1E, 0x3A, 0x8A)
ORANGE = RGBColor(0xEA, 0x58, 0x0C)
DARK_GRAY = RGBColor(0x37, 0x41, 0x51)
LIGHT_GRAY = RGBColor(0xF3, 0xF4, 0xF6)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)
ACCENT_LIGHT = RGBColor(0xDB, 0xE5, 0xFF)

prs = Presentation()
prs.slide_width = Inches(13.333)
prs.slide_height = Inches(7.5)


def add_blank():
    return prs.slides.add_slide(prs.slide_layouts[6])


def set_text(tf, text, size=18, bold=False, color=DARK_GRAY, align=PP_ALIGN.LEFT):
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = text
    p.font.size = Pt(size)
    p.font.bold = bold
    p.font.color.rgb = color
    p.alignment = align
    return p


def add_box(slide, x, y, w, h, fill=None, line=None):
    shape = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    if fill is not None:
        shape.fill.solid()
        shape.fill.fore_color.rgb = fill
    else:
        shape.fill.background()
    if line is not None:
        shape.line.color.rgb = line
        shape.line.width = Pt(0.75)
    else:
        shape.line.fill.background()
    return shape


def add_text(slide, x, y, w, h, text, size=18, bold=False, color=DARK_GRAY,
             align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    set_text(tf, text, size, bold, color, align)
    return tb


def add_paragraphs(slide, x, y, w, h, items, size=18, color=DARK_GRAY,
                   bullet=True, line_space=12):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        if i == 0:
            p = tf.paragraphs[0]
        else:
            p = tf.add_paragraph()
        prefix = "• " if bullet else ""
        p.text = prefix + item
        p.font.size = Pt(size)
        p.font.color.rgb = color
        p.space_after = Pt(line_space)
    return tb


def add_chapter_cover(chapter_num, title, subtitle=""):
    slide = add_blank()
    bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height)
    bg.fill.solid()
    bg.fill.fore_color.rgb = DEEP_BLUE
    bg.line.fill.background()
    bar = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(6.6),
                                  prs.slide_width, Inches(0.08))
    bar.fill.solid()
    bar.fill.fore_color.rgb = ORANGE
    bar.line.fill.background()
    add_text(slide, Inches(1), Inches(2.0), Inches(4), Inches(1.0),
             f"第 {chapter_num} 章", size=36, bold=True, color=ORANGE)
    add_text(slide, Inches(1), Inches(3.0), Inches(11), Inches(1.5),
             title, size=54, bold=True, color=WHITE)
    if subtitle:
        add_text(slide, Inches(1), Inches(4.6), Inches(11), Inches(1),
                 subtitle, size=24, color=WHITE)
    add_text(slide, Inches(1), Inches(6.85), Inches(11), Inches(0.4),
             "即学即用的问题解决工具箱", size=12, color=WHITE)


