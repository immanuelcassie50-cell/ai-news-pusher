def add_compare_table(title, headers, rows, page_num=0, total=130, chapter=""):
    slide = add_blank()
    top = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, Inches(0.18))
    top.fill.solid()
    top.fill.fore_color.rgb = DEEP_BLUE
    top.line.fill.background()
    add_text(slide, Inches(0.5), Inches(0.35), Inches(12.3), Inches(0.7),
             title, size=28, bold=True, color=DEEP_BLUE)
    line = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.5), Inches(1.05),
                                   Inches(2.0), Inches(0.06))
    line.fill.solid()
    line.fill.fore_color.rgb = ORANGE
    line.line.fill.background()
    n_cols = len(headers)
    col_w = 12.3 / n_cols
    y = Inches(1.4)
    for i, h in enumerate(headers):
        add_box(slide, Inches(0.5 + i * col_w), y, Inches(col_w), Inches(0.6),
                fill=DEEP_BLUE, line=DEEP_BLUE)
        add_text(slide, Inches(0.5 + i * col_w), y, Inches(col_w), Inches(0.6),
                 h, size=16, bold=True, color=WHITE, align=PP_ALIGN.CENTER,
                 anchor=MSO_ANCHOR.MIDDLE)
    row_h = (5.2) / max(len(rows), 1)
    for r, row in enumerate(rows):
        ry = Inches(2.0 + r * row_h)
        bg = LIGHT_GRAY if r % 2 == 0 else WHITE
        for c, cell in enumerate(row):
            add_box(slide, Inches(0.5 + c * col_w), ry, Inches(col_w), Inches(row_h),
                    fill=bg, line=DARK_GRAY)
            add_text(slide, Inches(0.5 + c * col_w), ry, Inches(col_w), Inches(row_h),
                     cell, size=14, color=DARK_GRAY, align=PP_ALIGN.CENTER,
                     anchor=MSO_ANCHOR.MIDDLE)
    add_text(slide, Inches(0.5), Inches(7.05), Inches(8), Inches(0.35),
             f"{chapter} | 即学即用的问题解决工具箱", size=10, color=DARK_GRAY)
    add_text(slide, Inches(11.5), Inches(7.05), Inches(1.5), Inches(0.35),
             f"{page_num} / {total}", size=10, color=DARK_GRAY, align=PP_ALIGN.RIGHT)


