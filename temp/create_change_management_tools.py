def create_shared_strings(items):
    """创建sharedStrings.xml"""
    unique = list(dict.fromkeys(items))  # Remove duplicates while preserving order
    count = len(items)
    unique_count = len(unique)

    xml = f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
    xml += f'<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="{count}" uniqueCount="{unique_count}">\n'
    for item in unique:
        escaped = item.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        xml += f'<si><t>{escaped}</t></si>\n'
    xml += '</sst>'
    return xml

def write_xlsx_file(filename, strings, data, col_widths=None):
    """将数据和样式写入xlsx文件"""
    output_dir = os.path.join(OUTPUT_BASE, filename)
    work_dir = "/tmp/xlsx_tool_work"
    shutil.rmtree(work_dir, ignore_errors=True)
    shutil.copytree(f"{SKILL_DIR}/templates/minimal_xlsx", work_dir)

    # Build sharedStrings
    shared_strings_xml = create_shared_strings(strings)
    with open(f"{work_dir}/xl/sharedStrings.xml", "w", encoding="utf-8") as f:
        f.write(shared_strings_xml)

    # Update workbook.xml for single sheet
    workbook_xml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"
          xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>
    <sheet name="Sheet1" sheetId="1" r:id="rId1"/>
  </sheets>
  <calcPr calcId="0"/>
</workbook>'''
    with open(f"{work_dir}/xl/workbook.xml", "w", encoding="utf-8") as f:
        f.write(workbook_xml)

    # Update workbook.xml.rels
    rels_xml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
  <Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
  <Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings" Target="sharedStrings.xml"/>
</Relationships>'''
    with open(f"{work_dir}/xl/_rels/workbook.xml.rels", "w", encoding="utf-8") as f:
        f.write(rels_xml)

    # Build string index
    string_idx = {s: i for i, s in enumerate(dict.fromkeys(strings))}

    # Build sheet1.xml
    sheet_xml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"
           xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheetViews><sheetView workbookViewId="0"/></sheetViews>
  <sheetFormatPr defaultRowHeight="15"/>
'''

    # Column widths
    if col_widths:
        sheet_xml += "  <cols>\n"
        for i, w in enumerate(col_widths, 1):
            sheet_xml += f'    <col min="{i}" max="{i}" width="{w}" customWidth="1"/>\n'
        sheet_xml += "  </cols>\n"

    sheet_xml += "  <sheetData>\n"

    for row_idx, row in enumerate(data, 1):
        sheet_xml += f'    <row r="{row_idx}">\n'
        for col_idx, val in enumerate(row, 1):
            col_letter = chr(64 + col_idx)
            cell_ref = f"{col_letter}{row_idx}"

            if isinstance(val, str):
                if val.startswith("="):
                    # Formula
                    sheet_xml += f'      <c r="{cell_ref}" s="6"><f>{val[1:]}</f><v></v></c>\n'
                elif val in string_idx:
                    idx = string_idx[val]
                    # Determine style based on row and content
                    if row_idx == 1:
                        s = "4"  # Header style
                    elif col_idx == 1 and val and not val.startswith(""):
                        s = "4"  # Section headers
                    else:
                        s = "0"  # Default
                    sheet_xml += f'      <c r="{cell_ref}" t="s" s="{s}"><v>{idx}</v></c>\n'
                else:
                    # Text value
                    idx = string_idx.get(val, 0)
                    s = "0"
                    sheet_xml += f'      <c r="{cell_ref}" t="s" s="{s}"><v>{idx}</v></c>\n'
            elif isinstance(val, (int, float)):
                if row_idx == 1:
                    s = "4"
                else:
                    s = "6"
                sheet_xml += f'      <c r="{cell_ref}" s="{s}"><v>{val}</v></c>\n'
            else:
                # Empty cell
                sheet_xml += f'      <c r="{cell_ref}" s="0"/>\n'
        sheet_xml += "    </row>\n"

    sheet_xml += "  </sheetData>\n"
    sheet_xml += '  <pageMargins left="0.7" right="0.7" top="0.75" bottom="0.75" header="0.3" footer="0.3"/>\n'
    sheet_xml += "</worksheet>"

    with open(f"{work_dir}/xl/worksheets/sheet1.xml", "w", encoding="utf-8") as f:
        f.write(sheet_xml)

    # Pack
    os.makedirs(os.path.dirname(output_dir), exist_ok=True)
    result = subprocess.run(
        ["python3", f"{SKILL_DIR}/scripts/xlsx_pack.py", work_dir, output_dir],
        capture_output=True, text=True
    )
    if result.returncode != 0:
        print(f"Error packing {filename}: {result.stderr}")
    else:
        print(f"Created: {filename}")

