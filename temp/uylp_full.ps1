function AddP($text, $size, $bold, $color, $bgColor) {
    $p = $doc.Content.Paragraphs.Add()
    $p.Range.Text = $text
    if ($size) { $p.Range.Font.Size = $size }
    if ($bold) { $p.Range.Font.Bold = $true }
    if ($color) { $p.Range.Font.Color = $color }
    if ($bgColor) { $p.Range.Shading.BackgroundPatternColor = $bgColor }
