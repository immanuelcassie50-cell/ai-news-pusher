# 创建文档函数
def create_case_document():
    doc = Document()

    # 设置默认字体
    style = doc.styles['Normal']
    style.font.name = '宋体'
    style.font.size = Pt(12)
    style._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

    # 设置页眉页脚
    section = doc.sections[0]
    header = section.header
    header.paragraphs[0].text = '变革管理精品案例集'
    header.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER

    footer = section.footer
    footer.paragraphs[0].text = f'第 {datetime.datetime.now().strftime("%Y")} 期 | 内部培训资料'
    footer.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER

    # 设置页面边距
    for section in doc.sections:
        section.top_margin = Cm(2.54)
        section.bottom_margin = Cm(2.54)
        section.left_margin = Cm(3.17)
        section.right_margin = Cm(3.17)

    return doc

def add_heading(doc, text, level=1):
    heading = doc.add_heading(text, level=level)
    heading.alignment = WD_ALIGN_PARAGRAPH.LEFT
    return heading

def add_paragraph(doc, text, first_line_indent=True):
    p = doc.add_paragraph(text)
    if first_line_indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    p.paragraph_format.line_spacing = 1.5
    return p

def add_bold_paragraph(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = True
    p.paragraph_format.first_line_indent = Cm(0.74)
    p.paragraph_format.line_spacing = 1.5
    return p

