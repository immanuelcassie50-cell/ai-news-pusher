        // ============ 核心框架速查 ============
        private static void WritePart3CoreFrameworkRef(Builder b)
        {
            b.H1("第三部分：核心框架速查（讲师参考）");
            b.P("本部分是讲师授课时的核心参考速查。授课时不需要照念，但需要随时能调用。");

            // 3.1 四步面谈法
            b.H2("3.1 四步面谈法（评估面谈主框架）");

            b.H3("第一步 · 共看事实");
            b.P("双方共同回顾这个考核周期里发生的可观察事实——行为、事件、结果——建立基于共同观察的对话基础。管理者不是\"宣告\"，而是\"邀请一起回顾\"。");
            b.P("关键原则：");
            b.BulletList(new[] {
                "描述行为，不做评判。",
                "具体到情境，不笼统概括。",
                "用\"我观察到……\"\"我看到的是……\"开头，不用\"我认为你……\"开头。"
            });
            b.PQuote("\"在开始今天的面谈之前，我想我们先一起回顾一下这个季度/年度。从你的角度，你觉得做到了什么，以及遇到了什么挑战？\"");
            b.P("讲师讲法：\"第一步的难点是——管理者很容易跳过去。直接说'你这个季度表现不错，但是……'，员工立刻进入防御。第一步是 5 分钟，但它直接决定后面 30 分钟的氛围。\"");

            b.H3("第二步 · 探寻归因（AI 时代新增）");
            b.P("共同探索\"这些事实背后，员工的人类贡献是什么\"——包括主动识别 AI 的参与程度。这一步是 AI 时代的新增，打开对话而不是单方面判断。");
            b.P("关键原则：");
            b.BulletList(new[] {
                "提问而非断言。",
                "好奇而非评判。",
                "对 AI 的参与保持开放而非预设立场。",
                "如果你的目的是\"找员工的漏洞\"，员工会感受到的。问这两个问题的最佳心态是\"我真的想理解你\"。"
            });
            b.PQuote("\"在你完成的这些里，你最满意的是哪个？在那个里，你的核心判断体现在哪里？\" / \"这个项目的结果很好，你觉得什么是只有你才能做到的这部分？\"");
            b.P("讲师讲法：\"第二步在 AI 时代是必须新增的。在没有 AI 的传统管理里，'员工的成果 = 员工的贡献'基本是成立的。AI 出现后，这个等式不再成立。如果你没有去探寻，你会基于一个你自己也不确定的事实做评估。\"");

            b.H3("第三步 · 分析缺口");
            b.P("基于归因清晰的事实，对照岗位要求和绩效目标，识别哪里的表现低于预期，以及缺口的性质是什么（技能缺口、行为缺口还是 AI 时代的工具能力缺口）。");
            b.P("关键原则：");
            b.BulletList(new[] {
                "从事实出发，不从印象出发。",
                "区分\"这次没做到\"和\"这个人这方面能力不足\"——前者是事件，后者是定性。",
                "缺口的四个层次：技能缺口（不会做）、行为缺口（知道但没做）、认知缺口（理解偏差导致的行为选择）、AI 时代的工具协作缺口（AI 协作能力不足导致的效率限制）。"
            });

            b.H3("第四步 · 共建方向");
            b.P("双方共同规划\"接下来怎么做\"——不只是管理者发布命令，而是一起找到双方都认为可行的改进步骤和支持安排。");
            b.P("关键原则：");
            b.BulletList(new[] {
                "问\"你觉得可以怎么做\"先于\"我要求你做什么\"。",
                "确认双方的具体行动，不只是意向。",
                "结束前必须有一个可衡量的下一步行动，而不是模糊的\"再努力\"。"
            });
            b.PQuote("\"在你看来，如果只能做一件事让下个季度不一样，你觉得是什么？\"");

            b.H2("3.2 正面·全面·情面·事面（艰难面谈核心原则）");

            b.H3("正面：直接说出问题");
            b.P("直接说出问题，不绕弯、不用暗示代替直说；当面说，不让员工听到传言。");
            b.P("AI 时代升级：在说出评估结论之前，先完成归因探寻，让\"正面说问题\"有可靠的事实基础。");
            b.Table(
                new[] { "说法 A（绕弯子）", "说法 B（正面直说）" },
                new List<string[]> {
                    new[] { "\"你这个季度总体还不错，但是……有一些地方……可能……你自己也感觉到了吧，有些地方还可以再努力一下……\"", "\"今天我想和你谈一件具体的事：你在 Q3 里三次客户汇报，客户反馈对方案里的商业分析部分不满意，我觉得这是一个需要我们正视的问题。\"" }
                }
            );
            b.P("讲师讲法：\"正面不是强硬，是让问题清晰。说法的对比要点：说法 A 的'但是'之后才是真话，'但是'之前全是铺垫——这种铺垫的代价是员工根本不知道你在说什么。\"");

            b.H3("全面：看到整体，不以偏概全");
            b.P("同时看到做到的和没做到的；不以单一事件定性；考虑外部因素的影响（包括 AI 工具的影响）。");
            b.P("AI 时代升级：全面还包括\"在 AI 辅助的情况下，员工的真实贡献被看到了\"——不要因为有 AI 就忽视真实存在的人类贡献。");
            b.Table(
                new[] { "说法 A（以偏概全）", "说法 B（全面）" },
                new List<string[]> {
                    new[] { "\"你总是不能按时提交，这说明你的时间管理有系统性的问题……\"", "\"你在 Q3 有三次提交延迟了，最长一次延迟了两天。但我也注意到你在同期接了额外的两个支持任务。我想了解一下，这三次延迟，你觉得是什么导致的？\"" }
                }
            );

            b.H3("情面：照顾情感，保护尊严");
