"""Generate all 7 missing 高管10大测评 xlsx files"""
import os, shutil, subprocess

OUT = r"D:\新课开发\测评表单"
TMP = r"D:\temp"

def find_pack_script():
    skill_base = r"C:\Users\Administrator\.claude\skills"
    for name in os.listdir(skill_base):
        full = os.path.join(skill_base, name)
        if os.path.isdir(full) and 'Excel' in name:
            pk = os.path.join(full, 'scripts', 'xlsx_pack.py')
            if os.path.exists(pk):
                return pk
    return None

PACK_SCRIPT = find_pack_script()

def sh(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return r.returncode == 0, r.stdout, r.stderr

def copy_template(num):
    src = r"D:\CC\temp\xlsx_work_01"
    dst = os.path.join(TMP, f"xg_{num:02d}")
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    return dst

def do_pack(work_num, title):
    wd = os.path.join(TMP, f"xg_{work_num:02d}")
    out_dir = os.path.join(OUT, "高管10大测评")
    out = os.path.join(out_dir, f"{work_num:02d}_{title}.xlsx")
    os.makedirs(out_dir, exist_ok=True)
    out_path = out.replace(os.sep, '/')
    wd_path = f"D:/temp/xg_{work_num:02d}"
    ok, out_log, err_log = sh(f'python3 "{PACK_SCRIPT}" "{wd_path}" "{out_path}"')
    if not ok:
        print(f"    pack err: {err_log[:200]}")
    return ok

def xml_esc(s):
    return s.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;")

def write_xml(path, content):
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

