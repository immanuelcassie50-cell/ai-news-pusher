# TOOL 2 — 股权激励成本计算器
# ════════════════════════════════════════════════════════════════════════════
h1("工具二：股权激励成本计算器")

body("**适用场景：** 财务/HR用本工具计算期权授予的公允价值、年度成本摊销及股权稀释比例，为财报披露和激励方案设计提供数据支撑。")

h2("2.1 期权价值计算 — Black-Scholes模型")

bold_body("参数说明:")
bullet("S = 当前股价（或评估公允价值）")
bullet("K = 行权价")
bullet("T = 期权有效期（年）")
bullet("r = 无风险利率（参考同期国债收益率）")
bullet("σ = 股价波动率（历史年化标准差）")

bold_body("期权价值公式:")
body("`C = S × N(d₁) - K × e^(-rT) × N(d₂)`")
body("`d₁ = [ln(S/K) + (r + σ²/2) × T] / (σ × √T)`")
body("`d₂ = d₁ - σ × √T`")
body("其中 N(·) 为标准正态分布累计概率函数，可用 Excel `=NORM.S.DIST(x, TRUE)` 计算。")

h2("2.2 稀释比例计算")

table(
    ["指标", "公式", "说明"],
    [
        ["授予期权总数", "—", "方案设定的期权总量"],
        ["稀释前总股本", "—", "公司现有流通股本（股数）"],
        ["稀释后总股本", "= 稀释前总股本 + 稀释期权对应的股数", "考虑行权后新增股份"],
        ["全面摊薄稀释率", "= 授予期权总数 / 稀释后总股本 × 100%", "IFRS 2 / ASC 718 要求"],
        ["加权平均稀释率", "= 稀释期权 × 归属期剩余月数 / 12 / 稀释前总股本 × 100%", "年度财报计算"],
    ]
)

h2("2.3 成本摊销计算")

bold_body("年度摊销 = 授予期权公允价值 × 归属期月数 / 总授予月数")
body("示例：某员工获授 10,000 股期权，公允价值 5 元/股，分 4 年归属（48 个月），当年在岗 9 个月：")
body("`年度摊销 = 10,000 × 5 × 9 / 48 = 9,375 元`")
body("Tip: 加速归属（如业绩加速条款）会导致前期摊销增大，需在授予时做前瞻估算。")

callout("合规提醒", "IFRS 2 和 ASC 718 均要求将股权激励计入经常性损益，建议在方案设计阶段就用本工具做三年成本预演，避免财报意外。")

