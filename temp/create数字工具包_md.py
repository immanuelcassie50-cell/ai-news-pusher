h1("工具五：激励ROI计算工具")

body("**适用场景：** 量化激励投入的回报，证明HR项目的商业价值，指导年度激励预算决策。")

h2("5.1 激励投入产出比")

bold_body("激励ROI = (激励带来的业绩增量 - 激励总成本) / 激励总成本 × 100%")
body("**分解步骤:**")
bullet("STEP 1 — 测算激励总成本：包括薪酬增量、股权摊销、福利支出、管理成本")
bullet("STEP 2 — 量化业绩增量：与基期对比，剥离市场增长因素后的纯激励贡献")
bullet("STEP 3 — 计算净收益：业绩增量 - 激励总成本")
bullet("STEP 4 — 计算ROI：净收益 / 激励总成本")
body("示例：某销售团队年度激励预算 50 万元，当年销售额增加 300 万元（扣除市场自然增长 100 万后，净增量 200 万）：")
body("`激励ROI = (200万 - 50万) / 50万 × 100% = 300%`")

h2("5.2 留任率改善计算")

bold_body("关键人才留任价值 = 替换成本 × 留任概率提升值")
body("其中替换成本通常为该岗位年薪的 50%~200%（管理岗取上限），留任概率提升值由激励方案实施前后对比得出。")

