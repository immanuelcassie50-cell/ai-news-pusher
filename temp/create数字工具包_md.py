body("`新薪 = MAX(现薪, 薪等下限) + 级差 × MIN(现薪 - 薪等下限, 带宽) / 带宽`")

bold_body("④ 重叠度检查:")
body("`重叠度 = (相邻薪等上限 - 本薪等下限) / (本薪等上限 - 本薪等下限) × 100%`")
body("推荐重叠度控制在 **20%~50%**，过高导致晋升激励弱化，过低导致薪酬刚性强。")

