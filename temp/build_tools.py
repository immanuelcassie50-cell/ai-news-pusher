def ss(itms):
    n = len(itms)
    L = ['<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="%d" uniqueCount="%d">' % (n,n)]
    for x in itms:
        x = x.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        L.append("  <si><t>%s</t></si>" % x)
    L.append("</sst>")
    return "\n".join(L)
def sh(rows):
    L = ["<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>",
         "<worksheet xmlns=\"http://schemas.openxmlformats.org/spreadsheetml/2006/main\" xmlns:r=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships\">",
         "  <sheetViews><sheetView workbookViewId=\"0\"/></sheetViews>",
         "  <sheetFormatPr defaultRowHeight=\"18\"/>",
         "  <cols>",
         '    <col min=\"1\" max=\"1\" width=\"4\" customWidth=\"1\"/>',
         '    <col min=\"2\" max=\"2\" width=\"22\" customWidth=\"1\"/>',
         '    <col min=\"3\" max=\"3\" width=\"40\" customWidth=\"1\"/>',
         '    <col min=\"4\" max=\"4\" width=\"18\" customWidth=\"1\"/>',
         "  </cols>",
         "  <sheetData>"]
    cr = None
    for rv, c, sy, *rk in rows:
        if rv != cr:
            if cr is not None: L.append("    </row>")
            L.append("    <row r=\"%d\">" % rv)
            cr = rv
        cl = chr(ord("A") + c - 1)
        if rk and isinstance(rk[0], str) and rk[0].startswith("="):
            L.append("      <c r=\"%s%d\" s=\"%d\"><f>%s</f><v></v></c>" % (cl, rv, sy, rk[0][1:]))
        elif rk:
            L.append("      <c r=\"%s%d\" s=\"%d\" t=\"s\"><v>%s</v></c>" % (cl, rv, sy, rk[0]))
        else:
            L.append("      <c r=\"%s%d\" s=\"%d\"/>" % (cl, rv, sy))
    if cr is not None: L.append("    </row>")
    L.append("  </sheetData>")
    L.append('  <pageMargins left=\"0.7\" right=\"0.7\" top=\"0.75\" bottom=\"0.75\" header=\"0.3\" footer=\"0.3\"/>')
    L.append("</worksheet>")
    return "\n".join(L)
def pk(d, o):
    with zipfile.ZipFile(o, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(d):
            for f in files:
                fp = os.path.join(root, f)
                z.write(fp, os.path.relpath(fp, d))
    print("Created: " + o)
