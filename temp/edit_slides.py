#!/usr/bin/env python3
"""Edit content of newly added slides."""
import re

UNPACKED_DIR = "D:/CC/temp/unpacked"

def edit_slide_text(slide_num, replacements):
    """Replace text in a slide. replacements is a dict of {old_text: new_text}"""
    slide_path = f"{UNPACKED_DIR}/ppt/slides/slide{slide_num}.xml"
    with open(slide_path, 'r', encoding='utf-8') as f:
        content = f.read()

    for old, new in replacements.items():
        content = content.replace(old, new)

    with open(slide_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Updated slide{slide_num}")

