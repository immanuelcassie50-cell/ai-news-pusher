for name, path in files:
    try:
        doc = Document(path)
        full_text = "\n".join([p.text for p in doc.paragraphs])
        answer_count = len(re.findall(r'答[：:]\s*\S', full_text))
        question_count = len(re.findall(r'^\d+[.、）)]', full_text, re.MULTILINE))

        if answer_count <= 3:
            risk = "高"
        elif question_count > 0 and answer_count < question_count * 0.3:
            risk = "中"
        else:
            risk = "低"
        print(f"第七组 | {name} | {question_count} | {answer_count} | {risk}")
    except Exception as e:
        print(f"第七组 | {name} | 错误: {e}")
