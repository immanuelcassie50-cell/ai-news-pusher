def apply_header_style(ws, row_num, num_cols):
    for col in range(1, num_cols + 1):
        cell = ws.cell(row=row_num, column=col)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.border = THIN_BORDER
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

def apply_data_style(ws, row_num, num_cols, alt_row=False):
    fill = ALT_ROW_FILL_2 if alt_row else ALT_ROW_FILL_1
    for col in range(1, num_cols + 1):
        cell = ws.cell(row=row_num, column=col)
        if cell.fill.patternType is None or cell.fill.fgColor.rgb == "00000000":
            cell.fill = fill
        cell.font = NORMAL_FONT
        cell.border = THIN_BORDER
        cell.alignment = Alignment(vertical="center", wrap_text=True)

